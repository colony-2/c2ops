package integration

import (
	"encoding/json"
	"strings"
	"testing"

	"github.com/colony-2/c2j/pkg/worker/compiler"
	"github.com/colony-2/jobdb/pkg/jobdb"
	"github.com/stretchr/testify/require"
)

func TestGeneratedBaseRequirementsReachAdmission(t *testing.T) {
	for _, base := range []string{"ubuntu-26.04-amd64", "ubuntu-26.04-arm64", "macos-26-arm64"} {
		t.Run(base, func(t *testing.T) {
			h := newHarness(t, nil)
			installJobFixture(t, h, "on: workflow_dispatch\njobs:\n  native:\n    runs-on: local\n    steps: [{run: 'exit 99'}]\n")
			installWorkflowFixture(t, h)
			recipe := workflowRecipe(t, "")
			start := strings.Index(recipe, "execution_needs:")
			require.NotEqual(t, -1, start)
			// Replace the single legacy requirement generated by workflowRecipe.
			lines := strings.Split(recipe, "\n")
			for i, line := range lines {
				if strings.Contains(line, "execution_needs:") {
					indent := line[:strings.Index(line, "execution_needs:")]
					lines[i] = indent + "execution_needs: {base: " + base + "}"
					for j := i + 1; j < len(lines) && strings.HasPrefix(lines[j], indent+"  "); j++ {
						lines[j] = ""
					}
				}
			}
			recipe = strings.Join(lines, "\n")
			root := h.submit(recipe, nil)
			h.step(root)
			found := false
			for iteration := 0; iteration < 4 && !found; iteration++ {
				for _, job := range h.jobs() {
					var meta struct {
						Recipe string `json:"recipe"`
					}
					require.NoError(t, json.Unmarshal(job.Metadata, &meta))
					if meta.Recipe == "gha-native" {
						h.step(job.JobKey)
					}
					if meta.Recipe == "gha-native-0" {
						out := h.step(job.JobKey)
						handoff, err := compiler.ExecutionHandoffFromOutcome(out)
						require.NoError(t, err)
						require.NotNil(t, handoff)
						require.Equal(t, base, *handoff.Demand.Effective.Base)
						require.NoError(t, h.db.CancelJob(h.ctx, jobdb.CancelJobRequest{JobKey: job.JobKey, Reason: "admission-only base fixture"}))
						run := h.drain(root)["run"].(map[string]any)
						logical := run["jobs"].(map[string]any)["native"].(map[string]any)
						instances := assertInstances(t, h, "native", logical, nil)
						instance := instances[0].(map[string]any)
						require.Equal(t, map[string]any{"base": base}, instance["execution_needs"])
						require.Equal(t, []any{"local"}, instance["labels"])
						require.Equal(t, job.JobKey.JobId, instance["execution_job_id"])
						require.Equal(t, "cancelled", instance["status"])
						saveEvidence(t, "base-"+base+"-result.json", map[string]any{"result": run, "admitted_base": *handoff.Demand.Effective.Base, "fixture": "base admission only; cancelled before invocation"})
						found = true
						break
					}
				}
			}
			require.True(t, found, "generated shard must reach native base admission")
		})
	}
}
